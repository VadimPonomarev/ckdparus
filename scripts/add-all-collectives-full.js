async function addAllCollectives() {
  console.log('🌱 Начинаем добавление всех коллективов с полными данными...\n');

  let addedCount = 0;
  let updatedCount = 0;

  for (const collective of ALL_COLLECTIVES) {
    try {
      // Проверяем, существует ли уже коллектив с таким slug
      const existing = await prisma.team.findUnique({
        where: { slug: collective.slug },
      });

      if (existing) {
        // Обновляем существующий коллектив
        await prisma.team.update({
          where: { id: existing.id },
          data: collective,
        });
        console.log(`🔄 Обновлен: ${collective.name}`);
        updatedCount++;
      } else {
        // Создаем новый коллектив
        const team = await prisma.team.create({
          data: {
            ...collective,
            isActive: true,
            status: 'active',
          },
        });

        console.log(`✅ Создан: ${team.name}`);
        addedCount++;
      }

      console.log(`   Slug: ${collective.slug}`);
      console.log(`   Категория: ${collective.category}`);
      console.log('-'.repeat(50));
    } catch (error) {
      console.error(`❌ Ошибка с "${collective.name}":`, error.message);
      console.log('-'.repeat(50));
    }
  }

  // Итоговая статистика
  console.log('\n📊 ИТОГОВАЯ СТАТИСТИКА:');
  console.log('='.repeat(30));
  console.log(`✅ Создано новых: ${addedCount}`);
  console.log(`🔄 Обновлено: ${updatedCount}`);
  console.log(`📋 Всего в базе: ${await prisma.team.count()} коллективов`);

  // Выводим примеры ID для тестирования
  console.log('\n🔗 Примеры ссылок для тестирования:');
  console.log('='.repeat(60));

  const sampleTeams = await prisma.team.findMany({
    take: 5,
    select: { id: true, name: true, slug: true },
    orderBy: { createdAt: 'desc' },
  });

  sampleTeams.forEach(team => {
    console.log(`${team.name}`);
    console.log(`ID: ${team.id}`);
    console.log(`Ссылка: http://localhost:3000/teams/${team.id}`);
    console.log('-'.repeat(60));
  });

  await prisma.$disconnect();
}

addAllCollectives();
